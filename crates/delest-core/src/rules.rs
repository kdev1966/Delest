pub fn rule_for(name: &str) -> Option<&'static Rule> {
    RULES.iter().find(|rule| rule.name == name)
}

/// A global cache, by its path below the home folder.
#[derive(Debug)]
pub struct CacheRule {
    pub path: &'static str,
    pub category: Category,
    pub verdict: Verdict,
    pub note: CacheNote,
}

const fn cache(
    path: &'static str,
    category: Category,
    verdict: Verdict,
    note: CacheNote,
) -> CacheRule {
    CacheRule {
        path,
        category,
        verdict,
        note,
    }
}

