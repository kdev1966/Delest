/// AI model files: never deleted, only deduplicated into the shared store.
pub fn is_model(name: &str) -> bool {
    [".gguf", ".safetensors", ".onnx"]
        .iter()
        .any(|extension| name.ends_with(extension))
}

/// Source files: a build folder without a manifest that holds them may be code.
pub fn is_source(name: &str) -> bool {
    const EXTENSIONS: [&str; 14] = [
        ".c", ".h", ".cc", ".cpp", ".hpp", ".rs", ".go", ".java", ".kt", ".swift", ".py", ".ts",
        ".dart", ".m",
    ];
    EXTENSIONS.iter().any(|extension| name.ends_with(extension)) && !name.ends_with(".d.ts")
}

/// Names that hold secrets, local configuration or data: never freed, wherever
/// they are found inside a build folder.
/// Folders a project needs that no build recreates: `Assets/` of a Unity project
/// holds its sources, `binaries/` of a Tauri app the programs it ships. The marker
/// beside them, when one is there.
pub fn project_part(path: &Path) -> Option<&'static str> {
    const PARTS: [(&str, &str); 2] = [
        ("Assets", "ProjectSettings"),
        ("binaries", "tauri.conf.json"),
    ];
    let name = path.file_name()?.to_str()?;
    let parent = path.parent()?;
    PARTS
        .iter()
        .find(|(part, marker)| *part == name && parent.join(marker).exists())
        .map(|(_, marker)| *marker)
}

pub fn is_sensitive(name: &str) -> bool {
    const EXTENSIONS: [&str; 7] = [".sqlite", ".sqlite3", ".db", ".pem", ".key", ".p12", ".jks"];
    const NAMES: [&str; 3] = [
        "local.properties",
        "google-services.json",
        "GoogleService-Info.plist",
    ];
    // Xcode keeps its own build index there; it is part of the build output.
    if name == "build.db" {
        return false;
    }
    name.starts_with(".env")
        || NAMES.contains(&name)
        || EXTENSIONS.iter().any(|extension| name.ends_with(extension))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rules_are_found_by_name() {
        assert_eq!(
            rule_for("node_modules").unwrap().category,
            Category::Dependencies
        );
        assert!(rule_for("src").is_none());
    }

    #[test]
    fn sensitive_names() {
        for name in [
            ".env",
            ".env.local",
            "app.db",
            "data.sqlite3",
            "server.pem",
            "local.properties",
        ] {
            assert!(is_sensitive(name), "{name}");
        }
        for name in ["build.db", "main.dart.js", "envelope.txt", "app.dbg"] {
            assert!(!is_sensitive(name), "{name}");
        }
    }
}
