//! The artefacts Delest knows: project folders recognised by their name and what
//! surrounds them, and global caches recognised by their place in the home folder.

use std::path::Path;

use crate::verdict::{CacheNote, Category, Verdict};

/// A file or folder next to an artefact that names the project's build tool.
#[derive(Debug)]
pub struct Manifest {
    pub file: &'static str,
    /// Outside git, whether this manifest alone proves the folder is an artefact.
    /// `package.json` does not: a `dist/` next to it may be a deliverable.
    pub conclusive: bool,
}

const fn conclusive(file: &'static str) -> Manifest {
    Manifest {
        file,
        conclusive: true,
    }
}

const fn hint(file: &'static str) -> Manifest {
    Manifest {
        file,
        conclusive: false,
    }
}

#[derive(Debug)]
pub enum Kind {
    /// Rebuilt locally by the project's build tool.
    Build,
    /// Regenerated by the interpreter.
    Bytecode,
    /// Regenerated by a development tool (test runner, type checker, linter).
    ToolCache,
    /// Reinstalled from the network; identical only with a lockfile.
    Dependencies {
        lockfiles: &'static [&'static str],
        /// Files that pin some versions only.
        partial: &'static [&'static str],
        /// A file the folder itself must hold to be what its name says.
        inside: Option<&'static str>,
    },
}

#[derive(Debug)]
pub struct Rule {
    pub name: &'static str,
    pub category: Category,
    pub kind: Kind,
    /// Looked for in the parent folder. Empty: no manifest is needed.
    pub manifests: &'static [Manifest],
    /// A new rule runs in shadow: its items are recognised but never offered,
    /// until the developer accepts it after the corpus replay.
    pub shadow: bool,
    /// Files inside that are the tool's own caches, not data: the ban on databases
    /// and secrets does not count them (Unity's `ShaderCache.db`).
    pub caches: &'static [&'static str],
}

